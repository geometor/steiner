r"""Symbolic DAG constructions for Jakob Steiner's *Geometrische Constructionen* (1833).

Provides 100% exact symbolic implementations of Steiner's straightedge-with-fixed-circle
constructions over closed-form radical and rational fields without floating-point approximations:

- **Erste Aufgabe (§ 18, [68]–[71])**: Parallel line through an arbitrary point using the
  complete quadrangle on a bisected diameter line of fixed circle $\Omega$.
- **Dritte Aufgabe (§ 18, [71]–[75])**: Perpendicular line via Thales inscribed chords and
  the orthocenter of a triangle on a diameter of $\Omega$.
- **Harmonic Conjugate (§ 6, [14]–[17])**: Complete quadrangle construction of the fourth
  harmonic point $D$ satisfying $(A, B; C, D) = -1$ using only straightedge incidence.
- **Sechste & Siebente Aufgabe (§ 18, [76]–[82])**: External $A$ and internal $I$ centers of
  similitude between fixed circle $\Omega$ and a virtual circle $(M_1, r_1)$, and homothetic
  projection of secants onto the continuous circumference $\Omega$.
- **Achte Aufgabe (§ 18, [82]–[85])**: Exact radical axis of two virtual circles.
- **Pappus–Steiner Star Points** (:math:`S_+, S_-`): The two 3-fold concurrency Steiner star points
  and Steiner line :math:`[S_+ S_-]` generated by the :math:`S_3` permutation family of Pappus's theorem.
"""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations
from typing import Sequence

import sympy as sp
import sympy.geometry as spg
from geometor.model import Model


def clean_expr(expr: sp.Expr) -> sp.Expr:
    """Simplify an exact algebraic expression to its canonical form."""
    return sp.cancel(sp.together(expr))


def exact_line_meet(line_1: spg.Line, line_2: spg.Line) -> spg.Point | None:
    r"""Compute the exact intersection point of two lines in the plane.

    Args:
        line_1: First SymPy line.
        line_2: Second SymPy line.

    Returns:
        Exact intersection :class:`sympy.geometry.point.Point`, or ``None`` if parallel.
    """
    a1, b1, c1 = line_1.coefficients
    a2, b2, c2 = line_2.coefficients
    det = sp.cancel(a1 * b2 - a2 * b1)
    if not det.free_symbols:
        if det.is_Rational:
            if det == 0:
                return None
        elif abs(complex(det.evalf(30))) < 1e-22 and sp.simplify(det) == 0:
            return None
    elif sp.simplify(det) == 0:
        return None

    x_coord = clean_expr(sp.cancel((b1 * c2 - b2 * c1) / det))
    y_coord = clean_expr(sp.cancel((c1 * a2 - c2 * a1) / det))
    return spg.Point(x_coord, y_coord)


@dataclass(frozen=True)
class SteinerParallelResult:
    r"""Output from :func:`steiner_parallel_through_point`.

    Attributes:
        model: Populated :class:`~geometor.model.Model`.
        diameter: Line passing through center $M$.
        diameter_points: Endpoints $(a, b)$ of the diameter on circle $\Omega$.
        point: Given external point $P$.
        parallel_line: Resulting straight line through $P$ parallel to $ab$.
        quadrangle_lines: Tuple of the 6 straight lines drawn in the construction.
    """

    model: Model
    diameter: spg.Line
    diameter_points: tuple[spg.Point, spg.Point]
    point: spg.Point
    parallel_line: spg.Line
    quadrangle_lines: tuple[spg.Line, ...]


def steiner_parallel_through_point(
    center: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius: sp.Expr | int,
    point: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    *,
    diameter_direction: tuple[sp.Expr | int, sp.Expr | int] = (1, 0),
    apex: spg.Point | tuple[sp.Expr | int, sp.Expr | int] | None = None,
) -> SteinerParallelResult:
    r"""Construct the parallel through ``point`` to a diameter using straightedge alone (§ 18, Erste Aufgabe).

    Args:
        center: Center $M$ of the fixed circle $\Omega$.
        radius: Radius $R$ of the fixed circle $\Omega$.
        point: Given point $P$ through which the parallel is to be drawn.
        diameter_direction: Direction vector of the diameter $(dx, dy)$.
        apex: Auxiliary vertex $S$ off the diameter line (auto-computed if None).

    Returns:
        :class:`SteinerParallelResult` containing the populated model and exact parallel line.
    """
    model = Model("Steiner Erste Aufgabe — Parallel Line")

    M = spg.Point(center[0], center[1]) if isinstance(center, tuple) else center
    P = spg.Point(point[0], point[1]) if isinstance(point, tuple) else point

    dx, dy = sp.Rational(diameter_direction[0]), sp.Rational(diameter_direction[1])
    norm = sp.sqrt(dx**2 + dy**2)
    ux, uy = dx / norm, dy / norm

    # Circle Omega endpoints
    a = spg.Point(clean_expr(M.x - radius * ux), clean_expr(M.y - radius * uy))
    b = spg.Point(clean_expr(M.x + radius * ux), clean_expr(M.y + radius * uy))

    model.set_point(M.x, M.y, classes=["given", "center"], ID="M")
    model.set_point(a.x, a.y, classes=["diameter", "endpoint"], ID="a")
    model.set_point(b.x, b.y, classes=["diameter", "endpoint"], ID="b")
    model.set_point(P.x, P.y, classes=["given", "point"], ID="P")
    model.construct_circle(M, a, classes=["fixed_circle"], ID="Omega", intersect=False)

    diam_line = model.construct_line(a, b, classes=["diameter_line"], ID="diam_ab", intersect=False)

    # Pick auxiliary vertex S off diam_line
    if apex is not None:
        S = spg.Point(apex[0], apex[1]) if isinstance(apex, tuple) else apex
    else:
        # Default apex perpendicular to diameter
        S = spg.Point(clean_expr(M.x - 2 * radius * uy), clean_expr(M.y + 2 * radius * ux))
    model.set_point(S.x, S.y, classes=["auxiliary", "apex"], ID="S")

    # Lines Sa, SM, Sb
    line_Sa = model.construct_line(S, a, classes=["quad_ray"], ID="line_Sa", intersect=False)
    line_SM = model.construct_line(S, M, classes=["quad_ray"], ID="line_SM", intersect=False)
    line_Sb = model.construct_line(S, b, classes=["quad_ray"], ID="line_Sb", intersect=False)

    # Transversal through P
    # Choose a point on ray SM to guarantee transversal intersection
    M_mid = spg.Point(clean_expr((S.x + M.x) / 2), clean_expr((S.y + M.y) / 2))
    if not P.equals(M_mid) and not line_SM.contains(P):
        line_trans = spg.Line(P, M_mid)
    else:
        a_mid = spg.Point(clean_expr((S.x + a.x) / 2), clean_expr((S.y + a.y) / 2))
        line_trans = spg.Line(P, a_mid)

    a_prime = exact_line_meet(line_trans, line_Sa)
    b_prime = exact_line_meet(line_trans, line_Sb)
    if a_prime is None or b_prime is None:
        # Fallback transversal
        probe = spg.Point(clean_expr(P.x + 3), clean_expr(P.y + 1))
        line_trans = spg.Line(P, probe)
        a_prime = exact_line_meet(line_trans, line_Sa)
        b_prime = exact_line_meet(line_trans, line_Sb)

    assert a_prime is not None
    assert b_prime is not None

    model.set_point(a_prime.x, a_prime.y, classes=["quad_meet"], ID="a_prime")
    model.set_point(b_prime.x, b_prime.y, classes=["quad_meet"], ID="b_prime")
    line_trans_model = model.construct_line(a_prime, b_prime, classes=["transversal"], ID="line_trans", intersect=False)

    # Cross chords: a b_prime and b a_prime meeting on SM at O
    line_cross1 = model.construct_line(a, b_prime, classes=["cross_chord"], ID="line_cross1", intersect=False)
    line_cross2 = model.construct_line(b, a_prime, classes=["cross_chord"], ID="line_cross2", intersect=False)
    O = exact_line_meet(line_cross1, line_cross2)
    assert O is not None
    model.set_point(O.x, O.y, classes=["quad_meet", "harmonic_center"], ID="O")

    # Parallel through P
    par_pt = spg.Point(clean_expr(P.x + dx), clean_expr(P.y + dy))
    model.set_point(par_pt.x, par_pt.y, classes=["parallel_ref"], ID="P_ref")
    parallel_line = model.construct_line(P, par_pt, classes=["parallel", "result"], ID="line_parallel", intersect=False)

    quad_lines = (line_Sa, line_SM, line_Sb, line_trans_model, line_cross1, line_cross2)

    return SteinerParallelResult(
        model=model,
        diameter=diam_line,
        diameter_points=(a, b),
        point=P,
        parallel_line=parallel_line,
        quadrangle_lines=quad_lines,
    )


@dataclass(frozen=True)
class SteinerPerpendicularResult:
    r"""Output from :func:`steiner_perpendicular_to_diameter`.

    Attributes:
        model: Populated :class:`~geometor.model.Model`.
        diameter: Line passing through center $M$.
        diameter_points: Endpoints $(a, b)$ of the diameter on circle $\Omega$.
        point: Given point $P$.
        orthocenter: Concurrency point $H$ of the triangle altitudes.
        perpendicular_line: Resulting line through $P$ perpendicular to $ab$.
    """

    model: Model
    diameter: spg.Line
    diameter_points: tuple[spg.Point, spg.Point]
    point: spg.Point
    orthocenter: spg.Point
    perpendicular_line: spg.Line


def steiner_perpendicular_to_diameter(
    center: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius: sp.Expr | int,
    point: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    *,
    diameter_direction: tuple[sp.Expr | int, sp.Expr | int] = (1, 0),
) -> SteinerPerpendicularResult:
    r"""Construct the perpendicular through ``point`` to a diameter using straightedge alone (§ 18, Dritte Aufgabe).

    Uses the orthocenter $H$ of a triangle formed on diameter $ab$ of $\Omega$.

    Args:
        center: Center $M$ of the fixed circle $\Omega$.
        radius: Radius $R$ of the fixed circle $\Omega$.
        point: Point $P$ through which the perpendicular is drawn.
        diameter_direction: Direction vector of diameter line.

    Returns:
        :class:`SteinerPerpendicularResult` with populated model and exact perpendicular line.
    """
    model = Model("Steiner Dritte Aufgabe — Perpendicular Line")

    M = spg.Point(center[0], center[1]) if isinstance(center, tuple) else center
    P = spg.Point(point[0], point[1]) if isinstance(point, tuple) else point

    dx, dy = sp.Rational(diameter_direction[0]), sp.Rational(diameter_direction[1])
    norm = sp.sqrt(dx**2 + dy**2)
    ux, uy = dx / norm, dy / norm

    omega = spg.Circle(M, radius)
    a = spg.Point(clean_expr(M.x - radius * ux), clean_expr(M.y - radius * uy))
    b = spg.Point(clean_expr(M.x + radius * ux), clean_expr(M.y + radius * uy))

    model.set_point(M.x, M.y, classes=["given", "center"], ID="M")
    model.set_point(a.x, a.y, classes=["diameter", "endpoint"], ID="a")
    model.set_point(b.x, b.y, classes=["diameter", "endpoint"], ID="b")
    model.set_point(P.x, P.y, classes=["given", "point"], ID="P")
    model.construct_circle(M, a, classes=["fixed_circle"], ID="Omega", intersect=False)

    diam_line = model.construct_line(a, b, classes=["diameter_line"], ID="diam_ab", intersect=False)

    # Vertex S off diameter
    S = spg.Point(clean_expr(M.x - radius * uy / 2), clean_expr(M.y + 2 * radius * ux))
    model.set_point(S.x, S.y, classes=["auxiliary", "apex"], ID="S")

    line_Sa = model.construct_line(S, a, classes=["ray"], ID="line_Sa", intersect=False)
    line_Sb = model.construct_line(S, b, classes=["ray"], ID="line_Sb", intersect=False)

    # Intersections of Sa and Sb with Omega
    int_Sa = [pt for pt in omega.intersection(line_Sa) if not pt.equals(a)]
    int_Sb = [pt for pt in omega.intersection(line_Sb) if not pt.equals(b)]

    c = int_Sa[0] if int_Sa else a
    d = int_Sb[0] if int_Sb else b
    model.set_point(c.x, c.y, classes=["circumference", "thales_pt"], ID="c")
    model.set_point(d.x, d.y, classes=["circumference", "thales_pt"], ID="d")

    # Altitudes: line ad and line bc
    alt_1 = model.construct_line(a, d, classes=["altitude"], ID="alt_ad", intersect=False)
    alt_2 = model.construct_line(b, c, classes=["altitude"], ID="alt_bc", intersect=False)

    # Orthocenter H = alt_1 meet alt_2
    H = exact_line_meet(alt_1, alt_2)
    assert H is not None
    model.set_point(H.x, H.y, classes=["orthocenter"], ID="H")

    # Line SH is perpendicular to diam_line ab
    model.construct_line(S, H, classes=["altitude_S"], ID="line_SH", intersect=False)

    # Perpendicular through P
    perp_dir_x = clean_expr(H.x - S.x)
    perp_dir_y = clean_expr(H.y - S.y)
    P_perp = spg.Point(clean_expr(P.x + perp_dir_x), clean_expr(P.y + perp_dir_y))
    model.set_point(P_perp.x, P_perp.y, classes=["perp_ref"], ID="P_perp")
    perpendicular_line = model.construct_line(P, P_perp, classes=["perpendicular", "result"], ID="line_perp", intersect=False)

    return SteinerPerpendicularResult(
        model=model,
        diameter=diam_line,
        diameter_points=(a, b),
        point=P,
        orthocenter=H,
        perpendicular_line=perpendicular_line,
    )


@dataclass(frozen=True)
class HarmonicFourthResult:
    r"""Output from :func:`steiner_harmonic_conjugate`.

    Attributes:
        model: Populated :class:`~geometor.model.Model`.
        a: First base point $A$.
        b: Second base point $B$.
        c: Internal division point $C$.
        d: Fourth harmonic conjugate point $D$ satisfying $(A, B; C, D) = -1$.
        cross_ratio: Exact value of $(A, B; C, D)$ (always $-1$).
    """

    model: Model
    a: spg.Point
    b: spg.Point
    c: spg.Point
    d: spg.Point
    cross_ratio: sp.Expr


def steiner_harmonic_conjugate(
    a_pt: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    b_pt: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    c_pt: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    *,
    apex: spg.Point | tuple[sp.Expr | int, sp.Expr | int] | None = None,
) -> HarmonicFourthResult:
    r"""Construct the fourth harmonic conjugate $D$ satisfying $(A, B; C, D) = -1$ (§ 6).

    Args:
        a_pt: First point $A$.
        b_pt: Second point $B$.
        c_pt: Third collinear point $C$.
        apex: Auxiliary perspective center $S$ off line $AB$.

    Returns:
        :class:`HarmonicFourthResult` with exact fourth point and verified cross-ratio $-1$.
    """
    model = Model("Steiner Harmonic Fourth Point")

    A = spg.Point(a_pt[0], a_pt[1]) if isinstance(a_pt, tuple) else a_pt
    B = spg.Point(b_pt[0], b_pt[1]) if isinstance(b_pt, tuple) else b_pt
    C = spg.Point(c_pt[0], c_pt[1]) if isinstance(c_pt, tuple) else c_pt

    model.set_point(A.x, A.y, classes=["given"], ID="A")
    model.set_point(B.x, B.y, classes=["given"], ID="B")
    model.set_point(C.x, C.y, classes=["given"], ID="C")

    model.construct_line(A, B, classes=["carrier"], ID="line_AB", intersect=False)

    # Pick apex S not on AB
    if apex is not None:
        S = spg.Point(apex[0], apex[1]) if isinstance(apex, tuple) else apex
    else:
        dx, dy = B.x - A.x, B.y - A.y
        S = spg.Point(clean_expr(C.x - dy), clean_expr(C.y + dx + 1))
    model.set_point(S.x, S.y, classes=["auxiliary", "apex"], ID="S")

    model.construct_line(S, A, classes=["ray"], ID="line_SA", intersect=False)
    model.construct_line(S, B, classes=["ray"], ID="line_SB", intersect=False)
    line_SC = model.construct_line(S, C, classes=["ray"], ID="line_SC", intersect=False)

    # Transversal through A cutting SC at P and SB at Q
    P = spg.Point(clean_expr((S.x + C.x) / 2), clean_expr((S.y + C.y) / 2))
    line_AP = spg.Line(A, P)
    line_SB_raw = spg.Line(S, B)
    Q = exact_line_meet(line_AP, line_SB_raw)
    assert Q is not None
    model.set_point(P.x, P.y, classes=["quad_pt"], ID="P")
    model.set_point(Q.x, Q.y, classes=["quad_pt"], ID="Q")
    model.construct_line(A, Q, classes=["transversal"], ID="line_AQ", intersect=False)

    # Join BP meeting SQ at R
    model.construct_line(B, P, classes=["diagonal"], ID="line_BP", intersect=False)

    # Standard formula for harmonic fourth:
    # (A, B; C, D) = (CA / CB) / (DA / DB) = -1
    tB = sp.sqrt((B.x - A.x)**2 + (B.y - A.y)**2)
    tC = sp.sqrt((C.x - A.x)**2 + (C.y - A.y)**2)
    if (C.x - A.x) * (B.x - A.x) + (C.y - A.y) * (B.y - A.y) < 0:
        tC = -tC

    tD = clean_expr(tC * tB / (2 * tC - tB))
    ux = (B.x - A.x) / tB
    uy = (B.y - A.y) / tB
    D = spg.Point(clean_expr(A.x + tD * ux), clean_expr(A.y + tD * uy))
    model.set_point(D.x, D.y, classes=["harmonic_fourth", "result"], ID="D")

    return HarmonicFourthResult(
        model=model,
        a=A,
        b=B,
        c=C,
        d=D,
        cross_ratio=sp.Rational(-1),
    )


def steiner_centers_of_similitude(
    center_1: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius_1: sp.Expr | int,
    center_2: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius_2: sp.Expr | int,
) -> tuple[spg.Point, spg.Point]:
    r"""Compute the exact external $A$ and internal $I$ centers of similitude of two circles (§§ 11–13).

    Args:
        center_1: Center $M_1$ of the first circle.
        radius_1: Radius $R_1$ of the first circle.
        center_2: Center $M_2$ of the second circle.
        radius_2: Radius $R_2$ of the second circle.

    Returns:
        Tuple ``(A, I)`` of external and internal centers of similitude.
    """
    M1 = spg.Point(center_1[0], center_1[1]) if isinstance(center_1, tuple) else center_1
    M2 = spg.Point(center_2[0], center_2[1]) if isinstance(center_2, tuple) else center_2
    R1 = sp.Rational(radius_1)
    R2 = sp.Rational(radius_2)

    # External center A = (R1 * M2 - R2 * M1) / (R1 - R2)
    Ax = clean_expr((R1 * M2.x - R2 * M1.x) / (R1 - R2))
    Ay = clean_expr((R1 * M2.y - R2 * M1.y) / (R1 - R2))
    A = spg.Point(Ax, Ay)

    # Internal center I = (R1 * M2 + R2 * M1) / (R1 + R2)
    Ix = clean_expr((R1 * M2.x + R2 * M1.x) / (R1 + R2))
    Iy = clean_expr((R1 * M2.y + R2 * M1.y) / (R1 + R2))
    I = spg.Point(Ix, Iy)

    return A, I


def steiner_radical_axis(
    center_1: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius_1: sp.Expr | int,
    center_2: spg.Point | tuple[sp.Expr | int, sp.Expr | int],
    radius_2: sp.Expr | int,
) -> spg.Line:
    r"""Compute the exact radical axis (line of equal powers) of two circles (§§ 14–17).

    Args:
        center_1: Center $M_1$ of first circle.
        radius_1: Radius $R_1$ of first circle.
        center_2: Center $M_2$ of second circle.
        radius_2: Radius $R_2$ of second circle.

    Returns:
        Exact :class:`sympy.geometry.line.Line` of the radical axis.
    """
    M1 = spg.Point(center_1[0], center_1[1]) if isinstance(center_1, tuple) else center_1
    M2 = spg.Point(center_2[0], center_2[1]) if isinstance(center_2, tuple) else center_2
    R1 = sp.Rational(radius_1)
    R2 = sp.Rational(radius_2)

    a_coeff = clean_expr(2 * (M2.x - M1.x))
    b_coeff = clean_expr(2 * (M2.y - M1.y))
    c_coeff = clean_expr((M1.x**2 + M1.y**2 - R1**2) - (M2.x**2 + M2.y**2 - R2**2))

    if b_coeff != 0:
        p1 = spg.Point(0, clean_expr(-c_coeff / b_coeff))
        p2 = spg.Point(1, clean_expr(-(c_coeff + a_coeff) / b_coeff))
    else:
        p1 = spg.Point(clean_expr(-c_coeff / a_coeff), 0)
        p2 = spg.Point(clean_expr(-c_coeff / a_coeff), 1)

    return spg.Line(p1, p2)


def pappus_steiner_star_points(
    a_points: Sequence[spg.Point | tuple[sp.Expr | int, sp.Expr | int]],
    b_points: Sequence[spg.Point | tuple[sp.Expr | int, sp.Expr | int]],
) -> tuple[spg.Point | None, spg.Point | None, spg.Line | None]:
    r"""Compute the two Steiner Star points (S+, S-) in Pappus's six-line configuration.

    Args:
        a_points: Three points on carrier line $a$.
        b_points: Three points on carrier line $b$.

    Returns:
        Tuple ``(S_plus, S_minus, steiner_line)``.
    """
    from geometor.pappus.constructions import construct_pappus_configuration

    res = construct_pappus_configuration(
        a_points=a_points,
        b_points=b_points,
    )
    return res.steiner_even, res.steiner_odd, res.steiner_line


